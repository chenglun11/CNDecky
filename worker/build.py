"""Bundle the shared, reviewed installer and launchers; never copy secrets or caches."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from cndecky.launcher import MODES, desktop_entry

PLACEHOLDER = "https://cndecky-origin.invalid"
client = (ROOT / "scripts/client.py").read_bytes()
bundle = {
    "placeholder": PLACEHOLDER,
    "client": client.decode(),
    "clientSha256": hashlib.sha256(client).hexdigest(),
    "installer": (ROOT / "scripts/install.sh").read_text(),
    "launchers": {mode: desktop_entry(PLACEHOLDER, mode) for mode in MODES},
}
(ROOT / "worker/generated.mjs").write_text(
    "// Generated by build.py from the shared installer. Do not edit.\n"
    "export default " + json.dumps(bundle, ensure_ascii=False) + ";\n"
)
